        $urlKey = strtolower(str_replace([' ', '&', 'í'], ['-', '', 'i'], $catName));
    }
    foreach ([0, 1] as $storeId) {
        try {
            $urlRewrite = $objectManager->create(\Magento\UrlRewrite\Model\UrlRewrite::class);
            $urlRewrite->setEntityType('category')
                ->setEntityId($catId)
                ->setRequestPath($urlKey . '.html')
                ->setTargetPath('catalog/category/view/id/' . $catId)
                ->setStoreId($storeId)
                ->setIsAutogenerated(1)
                ->setMetadata([]);
            $urlRewriteResource->save($urlRewrite);
            echo "    {$urlKey}.html -> catalog/category/view/id/{$catId}\n";
        } catch (\Magento\Framework\Exception\AlreadyExistsException $e) {
            echo "    {$urlKey}.html already exists (store $storeId)\n";
        }
    }
}

